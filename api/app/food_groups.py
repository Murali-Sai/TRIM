def _words(name: str) -> str:
    return " " + " ".join(re.findall(r"[a-z]+", name.lower().replace("-", " "))) + " "


def guess_group(name: str) -> str | None:
    """The first group with a keyword in the name, or None when nothing matches."""
    text = _words(name)
    for group, words in RULES:
        if any(f" {w.replace('-', ' ')} " in text for w in words):
            return group
    return None
